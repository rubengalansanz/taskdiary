-- 0001_init.sql — initial TaskDiary schema.
--
-- Created as a single migration on purpose (see odd/tasks/fase-1-datos.md, D1): the
-- plan already designs this exact schema in docs/plan-tasks-app.md §7.1, and plan rule
-- §2.8 forbids editing a published migration. Shipping it whole means there is one
-- place to audit the data model instead of a chain of partial migrations to reconstruct
-- it.
--
-- Date conventions (plan rule §2.7, ADR-003):
--   * task_date — local calendar day, 'YYYY-MM-DD'. Never an instant.
--   * start_min / end_min / estimate_min — integer minutes since midnight.
--   * created_at / updated_at / completed_at — ISO-8601 UTC, the only three columns
--     allowed to be instants.

CREATE TABLE tasks (
  id             TEXT PRIMARY KEY,           -- UUID v4, generated by the main process
  title          TEXT NOT NULL,
  notes          TEXT,
  task_date      TEXT NOT NULL,             -- 'YYYY-MM-DD', local calendar day
  status         TEXT NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending','in_progress','done','cancelled')),
  start_min      INTEGER,                   -- minutes since midnight
  end_min        INTEGER,                   -- NULL while the task has no end
  estimate_min   INTEGER,                   -- planned duration in minutes
  color          TEXT,                      -- optional user colour
  -- recurrence: one row per series, not one per occurrence (ADR-004)
  rrule_freq     TEXT NOT NULL DEFAULT 'none'
                 CHECK (rrule_freq IN ('none','daily','weekly','monthly','weekdays')),
  rrule_interval INTEGER NOT NULL DEFAULT 1,
  rrule_days     TEXT,                      -- CSV of ISO weekdays, '1'=Monday
  rrule_until    TEXT,                      -- 'YYYY-MM-DD', inclusive
  rrule_from     TEXT,                      -- 'YYYY-MM-DD', origin of the series
  -- audit
  created_at     TEXT NOT NULL,             -- ISO-8601 UTC
  updated_at     TEXT NOT NULL,             -- ISO-8601 UTC
  completed_at   TEXT,                      -- ISO-8601 UTC or NULL

  -- A recurring task must carry the origin of its series; a one-off must not. Without
  -- this, `idx_tasks_occurrence` would treat unrelated tasks as occurrences of the same
  -- series and reject perfectly valid rows.
  CHECK (rrule_freq = 'none' OR rrule_from IS NOT NULL)
);

-- Day view reads by date; the composite index serves the per-status filters of Fase 3.
CREATE INDEX idx_tasks_date        ON tasks (task_date);
CREATE INDEX idx_tasks_date_status ON tasks (task_date, status);

-- Partial index: the streak aggregate only ever touches completed rows.
CREATE INDEX idx_tasks_completed   ON tasks (completed_at)
                                   WHERE completed_at IS NOT NULL;

-- Enforces the focus rule (RF-03) at the storage layer: at most one `in_progress` task
-- per calendar day. The application checks the same rule in `core/validation.ts` to
-- produce a friendly `FOCUS_ALREADY_SET` error, but only the index closes the race
-- between two concurrent status changes — a check-then-write in application code cannot.
CREATE UNIQUE INDEX idx_tasks_single_focus
  ON tasks (task_date)
  WHERE status = 'in_progress';

-- Guarantees a recurring occurrence is materialised at most once, even if a crash
-- replays the materialisation (plan §16, risk 7).
CREATE UNIQUE INDEX idx_tasks_occurrence
  ON tasks (rrule_from, task_date)
  WHERE rrule_from IS NOT NULL;

CREATE TABLE tags (
  id    TEXT PRIMARY KEY,
  name  TEXT NOT NULL UNIQUE,               -- stored without the leading '#'
  color TEXT
);

CREATE TABLE task_tags (
  task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  tag_id  TEXT NOT NULL REFERENCES tags(id)  ON DELETE CASCADE,
  PRIMARY KEY (task_id, tag_id)
);

-- Reverse lookup: "which tasks carry this tag" is the Fase 3 filter query.
CREATE INDEX idx_task_tags_tag ON task_tags (tag_id);

CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL                       -- JSON-encoded value
);